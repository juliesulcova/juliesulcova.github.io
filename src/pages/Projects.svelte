    <p>Workshop before the performance, i.e. working with the audience that is about to become the audience. Therefore,
      the goal is to provide support and impulses for better/wider perception of the future viewer's experience.</p>

    <p>Within the workshop, the creative team decided to emphasize the theme of collective harmony contrasted
      with individual movement. The age group participating in the workshops was 14–21 years.</p>

    <p>The educational goal was:</p>

    <ul>
      <li>to familiarize participants with the principles of physical theatre and polyphony through specific practical exercises,</li>
      <li>to familiarize participants with the type of performance whose meaning is based on free audience interpretation,</li>
      <li>to build audience competence associated with perceiving specific features of the performance.</li>
    </ul>

    <p><strong>Sbor</strong> is a final-year production of students of Physical Theatre at DF JAMU. It is a production
      based on the principle of polyphony, which combines classical physical theatre, based on expressing and
      interpreting stories through body movement, with a strongly musical layer, creating a very specific
      theatrical concept. It has no specific storyline. It is an organic theatrical form based on
      the atmosphere of a polyphonic whole, which allows the viewer to find their own stories and
      connections within it.</p>

    <p><strong>Workshop content:</strong></p>

    <ul>
      <li><strong>INTRODUCTION</strong> – getting to know each other, explaining why we meet.</li>
      <li><strong>MAIN PART</strong> – two movement-creative exercises. One for group work, the other for working with
        associations emphasizing the difference in individual perception of the world.</li>
      <li><strong>REFLECTION</strong> – discovering insights from the exercises and applying findings to the principles of the Sbor performance.</li>
    </ul>

